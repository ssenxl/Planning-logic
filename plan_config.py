def show(spec, v) -> str:
    """ค่า → ข้อความที่คนอ่านรู้เรื่อง (ใช้ทั้งใน log และหน้าเว็บ)"""
    if spec["type"] == "bool":
        return "เปิด" if v else "ปิด"
    if spec["type"] == "list":
        items = v or []
        if not items:
            return "ไม่มีรายการ"
        head = ", ".join(str(x) for x in items[:4])
        return f"{len(items)} รายการ: {head}" + (" …" if len(items) > 4 else "")
    if spec["type"] == "table":
        rows = v or []
        if not rows:
            return "ไม่มีรายการ"
        keys = spec.get("show_cols") or [c["key"] for c in spec.get("columns", [])[:2]]
        first = rows[0]
        head = " → ".join(str(first.get(k, "")) for k in keys if str(first.get(k, "")) != "")
        return f"{len(rows)} รายการ" + (f" (เช่น {head})" if head else "")
    if v is None or v == "":
        return "ไม่จำกัด"
    if spec["type"] == "float":
        v = round(float(v), 2)
        v = int(v) if float(v).is_integer() else v
    return f"{v} {spec.get('unit', '')}".strip()


def non_default_lines() -> list:
    """บรรทัดสรุป "ค่าที่ไม่ใช่ค่ามาตรฐาน" — runner พิมพ์ลง log ทุกรอบรัน
    จะได้ย้อนดูได้ว่าแผนรอบนั้นรันด้วยค่าอะไร"""
    out = []
    for s in SPEC:
        src = source_of(s["key"])
        if src == "default":
            continue
        tag = "env" if src == "env" else "เว็บ"
        out.append(f"{s['label']} = {show(s, get(s['key']))} "
                   f"(มาตรฐาน {show(s, s['default'])}) [{tag}]")
    return out


