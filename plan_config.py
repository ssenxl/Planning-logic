def _parse_bool(raw, default):
    s = str(raw).strip().lower()
    if s in TRUE_WORDS:
        return True
    if s in FALSE_WORDS:
        return False
    return default


def _parse_num(raw, spec):
    """แปลงเป็นตัวเลขตามกติกาของ key นั้น — แปลงไม่ได้ = คืนค่ามาตรฐาน, นอกช่วง = หนีบเข้าช่วง"""
    s = str(raw).strip()
    if s == "":
        return None if spec.get("blank") else spec["default"]
    try:
        v = float(s)
    except (TypeError, ValueError):
        return spec["default"]
    if spec["type"] == "int":
        v = int(v)
    lo, hi = spec.get("min"), spec.get("max")
    if lo is not None and v < lo:
        return lo if spec["type"] != "int" else int(lo)
    if hi is not None and v > hi:
        return hi if spec["type"] != "int" else int(hi)
    return v


def _parse_list(raw, spec):
    """รายชื่อ → list — รับได้ทั้ง list จริง และข้อความคั่นด้วยจุลภาค (เผื่อสั่งทับจาก env)"""
    items = raw if isinstance(raw, list) else str(raw).split(",")
    out = []
    for it in items:
        s = str(it).strip()
        if not s:
            continue
        if spec.get("item_type") == "int":
            try:
                out.append(int(float(s)))
            except (TypeError, ValueError):
                continue
        else:
            out.append(s)
    return out


def _parse_table(raw, spec):
    """ตาราง → list ของ dict ตามคอลัมน์ที่ประกาศไว้ (คอลัมน์แปลก ๆ ถูกตัดทิ้ง)"""
    rows = raw
    if isinstance(rows, str):
        try:
            rows = json.loads(rows)
        except Exception:
            return list(spec["default"])
    if not isinstance(rows, list):
        return list(spec["default"])
    cols = spec.get("columns", [])
    out = []
    for r in rows:
        if not isinstance(r, dict):
            continue
        row, empty = {}, True
        for c in cols:
            v = r.get(c["key"], "")
            s = "" if v is None else str(v).strip()
            if c.get("type") == "int":
                try:
                    row[c["key"]] = int(float(s)) if s != "" else 0
                except (TypeError, ValueError):
                    row[c["key"]] = 0
            else:
                row[c["key"]] = s
            if s != "":
                empty = False
        if not empty:
            out.append(row)
    return out


def _coerce(spec, raw):
    t = spec["type"]
    if t == "bool":
        return _parse_bool(raw, spec["default"])
    if t == "list":
        return _parse_list(raw, spec)
    if t == "table":
        return _parse_table(raw, spec)
    return _parse_num(raw, spec)


def load_file() -> dict:
    """ค่าที่ผู้ใช้บันทึกไว้ (ดิบ ๆ จากไฟล์) — ไฟล์ยังไม่มี/พังก็คืน {} ไม่โยน exception
    (pipeline ต้องรันได้เสมอแม้ไฟล์ config หาย)"""
    try:
        if CONFIG_FILE.exists():
            data = json.loads(CONFIG_FILE.read_text(encoding="utf-8"))
            if isinstance(data, dict):
                return {k: v for k, v in data.get("values", data).items() if k in BY_KEY}
    except Exception as e:
        print(f"⚠️ อ่าน {CONFIG_FILE.name} ไม่ได้ ({e}) → ใช้ค่ามาตรฐาน")
    return {}


_FILE_VALUES = load_file()


def source_of(key: str) -> str:
    """ค่านี้มาจากไหน: env (ทับไว้จากภายนอก) / file (ตั้งจากหน้าเว็บ) / default"""
    if os.environ.get(key, "").strip() != "":
        return "env"
    return "file" if key in _FILE_VALUES else "default"


def get(key: str):
    """ค่าที่ใช้จริง ตามลำดับ env > ไฟล์ > ค่ามาตรฐาน
    key ที่ยังไม่มีในทะเบียน (โค้ดเก่า/ใหม่ไม่ตรงกัน) → คืนค่า env ดิบ หรือ None — ไม่ล้ม"""
    spec = BY_KEY.get(key)
    if spec is None:
        return os.environ.get(key) or None
    env_raw = os.environ.get(key, "").strip()
    if env_raw != "":
        return _coerce(spec, env_raw)
    if key in _FILE_VALUES:
        return _coerce(spec, _FILE_VALUES[key])
    return spec["default"]


def ratio(key: str) -> float:
    """ค่าที่เก็บเป็น % (0-100) → สัดส่วน 0-1 สำหรับใช้คำนวณ"""
    v = get(key)
    return (float(v) if v is not None else 0.0) / 100.0


def get_list(key: str, upper: bool = False) -> list:
    """รายชื่อ → list (upper=True สำหรับค่าที่โค้ดเทียบแบบตัวพิมพ์ใหญ่ เช่น ชื่อกลุ่มเครื่อง)"""
    out = get(key) or []
    return [str(v).strip().upper() for v in out] if upper else list(out)


def get_rows(key: str) -> list:
    """ตาราง → list ของ dict (คอลัมน์ตามที่ประกาศใน SPEC)"""
    return list(get(key) or [])


