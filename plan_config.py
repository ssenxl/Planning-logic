def validate(values: dict) -> tuple:
    """ตรวจค่าที่ส่งมา → (ค่าที่สะอาดแล้ว, รายการ error)
    key ที่ไม่รู้จักถูกทิ้งเงียบ ๆ (เวอร์ชันหน้าเว็บอาจเก่ากว่า backend)"""
    clean, errors = {}, []
    for key, raw in (values or {}).items():
        spec = BY_KEY.get(key)
        if spec is None:
            continue
        if spec["type"] == "bool":
            if isinstance(raw, bool):
                clean[key] = raw
            else:
                s = str(raw).strip().lower()
                if s not in TRUE_WORDS + FALSE_WORDS:
                    errors.append(f"{spec['label']}: ต้องเป็นเปิด/ปิด")
                    continue
                clean[key] = s in TRUE_WORDS
            continue

        if spec["type"] == "list":
            if not isinstance(raw, list):
                errors.append(f"{spec['label']}: รูปแบบรายการไม่ถูกต้อง")
                continue
            vals, bad = [], False
            for it in raw:
                s = str(it).strip()
                if s == "":
                    continue                      # ช่องว่าง = ผู้ใช้ยังไม่พิมพ์ ตัดทิ้งเงียบ ๆ
                if spec.get("item_type") == "int":
                    try:
                        s = int(float(s))
                    except (TypeError, ValueError):
                        errors.append(f"{spec['label']}: '{s}' ไม่ใช่ตัวเลข")
                        bad = True
                        break
                if s not in vals:                 # กันซ้ำ
                    vals.append(s)
            if not bad:
                clean[key] = vals
            continue

        if spec["type"] == "table":
            if not isinstance(raw, list):
                errors.append(f"{spec['label']}: รูปแบบตารางไม่ถูกต้อง")
                continue
            cols = spec.get("columns", [])
            rows, bad = [], False
            for n, r in enumerate(raw, 1):
                if not isinstance(r, dict):
                    continue
                vals = {c["key"]: str(r.get(c["key"], "") or "").strip() for c in cols}
                if all(v == "" for v in vals.values()):
                    continue                      # แถวเปล่า = ผู้ใช้กดเพิ่มแล้วยังไม่กรอก
                miss = [c["label"] for c in cols if vals[c["key"]] == "" and not c.get("optional")]
                if miss:
                    errors.append(f"{spec['label']} แถวที่ {n}: ยังไม่ได้กรอก {', '.join(miss)}")
                    bad = True
                    break
                wrong = [c["label"] for c in cols if c.get("choices") and vals[c["key"]] != ""
                         and vals[c["key"]] not in {ch["value"] for ch in c["choices"]}]
                if wrong:
                    errors.append(f"{spec['label']} แถวที่ {n}: {', '.join(wrong)} ต้องเลือกจากตัวเลือก")
                    bad = True
                    break
                row = {}
                for c in cols:
                    if c.get("type") == "int":
                        try:
                            row[c["key"]] = int(float(vals[c["key"]]))
                        except (TypeError, ValueError):
                            errors.append(f"{spec['label']} แถวที่ {n}: {c['label']} ต้องเป็นตัวเลข")
                            bad = True
                            break
                    else:
                        row[c["key"]] = vals[c["key"]]
                if bad:
                    break
                rows.append(row)
            if not bad:
                clean[key] = rows
            continue

        s = "" if raw is None else str(raw).strip()
        if s == "":
            if not spec.get("blank"):
                errors.append(f"{spec['label']}: ต้องใส่ตัวเลข")
                continue
            clean[key] = None
            continue
        try:
            v = float(s)
        except (TypeError, ValueError):
            errors.append(f"{spec['label']}: ต้องเป็นตัวเลข")
            continue
        if spec["type"] == "int":
            if v != int(v):
                errors.append(f"{spec['label']}: ต้องเป็นจำนวนเต็ม")
                continue
            v = int(v)
        lo, hi = spec.get("min"), spec.get("max")
        if (lo is not None and v < lo) or (hi is not None and v > hi):
            errors.append(f"{spec['label']}: ใส่ได้ระหว่าง {lo} ถึง {hi}")
            continue
        clean[key] = v
    return clean, errors


def save(values: dict, user: str = "") -> dict:
    """บันทึกค่าลงไฟล์ (สำรองไฟล์เดิมเป็น .bak ก่อน) + จดประวัติว่าใครแก้อะไร
    คืน {ok, saved, changed:[...], errors:[...]}
    ⚠️ ค่าที่ตรงกับค่ามาตรฐานจะไม่ถูกเขียนลงไฟล์ — ไฟล์เก็บเฉพาะ "สิ่งที่ตั้งเอง"
       ทำให้เวลาเราปรับค่ามาตรฐานในโค้ดภายหลัง ค่าที่ผู้ใช้ไม่เคยแตะจะขยับตามเอง"""
    global _FILE_VALUES
    clean, errors = validate(values)
    if errors:
        return {"ok": False, "errors": errors}

    before = dict(_FILE_VALUES)
    keep = {k: v for k, v in clean.items() if v != BY_KEY[k]["default"]}

    changed = []
    for key, spec in BY_KEY.items():
        old = before.get(key, spec["default"])
        new = keep.get(key, spec["default"])
        if old != new:
            changed.append({
                "key": key, "label": spec["label"],
                "from": old, "to": new,
                "from_text": show(spec, old), "to_text": show(spec, new),
            })

    CONFIG_FILE.parent.mkdir(parents=True, exist_ok=True)
    if CONFIG_FILE.exists():
        try:
            CONFIG_FILE.with_suffix(CONFIG_FILE.suffix + ".bak").write_text(
                CONFIG_FILE.read_text(encoding="utf-8"), encoding="utf-8"
            )
        except Exception:
            pass

    payload = {
        "updated_at": datetime.now().isoformat(timespec="seconds"),
        "updated_by": user,
        "values": keep,
    }
    CONFIG_FILE.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    _FILE_VALUES = dict(keep)

    if changed:
        _append_log({"at": payload["updated_at"], "by": user, "changed": changed})
    return {"ok": True, "saved": len(keep), "changed": changed}


def _append_log(entry: dict) -> None:
    try:
        with open(LOG_FILE, "a", encoding="utf-8") as f:
            f.write(json.dumps(entry, ensure_ascii=False) + "\n")
    except Exception:
        pass


def history(limit: int = 50) -> list:
    """ประวัติการแก้ล่าสุด (ใหม่สุดอยู่บน) ; limit <= 0 = ทั้งหมด"""
    if not LOG_FILE.exists():
        return []
    out = []
    try:
        for line in LOG_FILE.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if not line:
                continue
            try:
                out.append(json.loads(line))
            except Exception:
                continue
    except Exception:
        return []
    return (out[-limit:] if limit > 0 else out)[::-1]


